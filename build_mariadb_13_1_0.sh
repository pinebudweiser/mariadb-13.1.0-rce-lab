#!/usr/bin/env bash
# WSL/Linux: fetch the same source revision and install under SOURCE_DIR/inst.
set -Eeuo pipefail

REVISION=91f37a32f3ee463bdb8287ef951170b5f64201e0
SOURCE_DIR="${SOURCE_DIR:-$PWD/mariadb-13.1.0-git}"
JOBS="${JOBS:-2}"
[[ "$JOBS" =~ ^[1-9][0-9]*$ ]] || { echo 'JOBS must be a positive integer.' >&2; exit 1; }
[[ ! -e "$SOURCE_DIR" && ! -L "$SOURCE_DIR" ]] || {
  echo "Directory already exists: $SOURCE_DIR" >&2
  exit 1
}
for tool in git cmake make; do command -v "$tool" >/dev/null; done
C_COMPILER="$(command -v "${CC:-cc}")"
CXX_COMPILER="$(command -v "${CXX:-c++}")"
C_COMPILER="$(realpath "$C_COMPILER")"
CXX_COMPILER="$(realpath "$CXX_COMPILER")"

git clone --filter=blob:none --no-checkout https://github.com/MariaDB/server.git "$SOURCE_DIR"
SOURCE_DIR="$(cd "$SOURCE_DIR" && pwd -P)"
git -C "$SOURCE_DIR" checkout --detach "$REVISION"
[[ "$(git -C "$SOURCE_DIR" rev-parse HEAD)" == "$REVISION" ]]
git -C "$SOURCE_DIR" submodule update --init --recursive

BUILD_DIR="$SOURCE_DIR/bld"
PREFIX="$SOURCE_DIR/inst"
# Retain the feature options from the supplied build script.
CMAKE_OPTIONS=(
  "-DCMAKE_BUILD_TYPE=RelWithDebInfo"
  "-DCMAKE_INSTALL_PREFIX=$PREFIX"
  "-DINSTALL_LAYOUT=STANDALONE"
  "-DCMAKE_C_COMPILER=$C_COMPILER"
  "-DCMAKE_CXX_COMPILER=$CXX_COMPILER"
  "-DCONNECT_WITH_BSON=ON"
  "-DCONNECT_WITH_JDBC=ON"
  "-DCONNECT_WITH_LIBXML2=ON"
  "-DCONNECT_WITH_MONGO=ON"
  "-DCONNECT_WITH_ODBC=ON"
  "-DCONNECT_WITH_REST=ON"
  "-DCONNECT_WITH_VCT=ON"
  "-DCONNECT_WITH_XMAP=ON"
  "-DCONNECT_WITH_ZIP=ON"
  "-DENABLED_JSON_WRITER_CONSISTENCY_CHECKS=OFF"
  "-DENABLED_LOCAL_INFILE=AUTO"
  "-DENABLED_PROFILING=ON"
  "-DPLUGIN_ARCHIVE=DYNAMIC"
  "-DPLUGIN_AUDIT_NULL=DYNAMIC"
  "-DPLUGIN_AUTH_0X0100=DYNAMIC"
  "-DPLUGIN_AUTH_ED25519=DYNAMIC"
  "-DPLUGIN_AUTH_MYSQL_SHA2=DYNAMIC"
  "-DPLUGIN_AUTH_PARSEC=DYNAMIC"
  "-DPLUGIN_AUTH_SOCKET=STATIC"
  "-DPLUGIN_AUTH_TEST_PLUGIN=DYNAMIC"
  "-DPLUGIN_BLACKHOLE=DYNAMIC"
  "-DPLUGIN_COLUMNSTORE=NO"
  "-DPLUGIN_CONNECT=DYNAMIC"
  "-DPLUGIN_DAEMON_EXAMPLE=DYNAMIC"
  "-DPLUGIN_DEBUG_KEY_MANAGEMENT=DYNAMIC"
  "-DPLUGIN_DIALOG_EXAMPLES=DYNAMIC"
  "-DPLUGIN_DISKS=DYNAMIC"
  "-DPLUGIN_EXAMPLE=DYNAMIC"
  "-DPLUGIN_EXAMPLE_KEY_MANAGEMENT=DYNAMIC"
  "-DPLUGIN_FEDERATED=DYNAMIC"
  "-DPLUGIN_FEDERATEDX=DYNAMIC"
  "-DPLUGIN_FEEDBACK=STATIC"
  "-DPLUGIN_FILE_KEY_MANAGEMENT=DYNAMIC"
  "-DPLUGIN_FTEXAMPLE=DYNAMIC"
  "-DPLUGIN_FUNC_TEST=DYNAMIC"
  "-DPLUGIN_HANDLERSOCKET=DYNAMIC"
  "-DPLUGIN_INNOBASE=NO"
  "-DPLUGIN_LOCALES=DYNAMIC"
  "-DPLUGIN_METADATA_LOCK_INFO=DYNAMIC"
  "-DPLUGIN_MROONGA=NO"
  "-DPLUGIN_OQGRAPH=NO"
  "-DPLUGIN_PARTITION=STATIC"
  "-DPLUGIN_PASSWORD_REUSE_CHECK=DYNAMIC"
  "-DPLUGIN_PERFSCHEMA=STATIC"
  "-DPLUGIN_QA_AUTH_CLIENT=DYNAMIC"
  "-DPLUGIN_QA_AUTH_INTERFACE=DYNAMIC"
  "-DPLUGIN_QA_AUTH_SERVER=DYNAMIC"
  "-DPLUGIN_QUERY_CACHE_INFO=DYNAMIC"
  "-DPLUGIN_QUERY_RESPONSE_TIME=DYNAMIC"
  "-DPLUGIN_ROCKSDB=NO"
  "-DPLUGIN_SEQUENCE=STATIC"
  "-DPLUGIN_SERVER_AUDIT=DYNAMIC"
  "-DPLUGIN_SIMPLE_PASSWORD_CHECK=DYNAMIC"
  "-DPLUGIN_SPHINX=NO"
  "-DPLUGIN_SPIDER=NO"
  "-DPLUGIN_SQL_ERRLOG=DYNAMIC"
  "-DPLUGIN_TEST_SQL_DISCOVERY=DYNAMIC"
  "-DPLUGIN_TEST_SQL_SERVICE=DYNAMIC"
  "-DPLUGIN_TEST_VERSIONING=DYNAMIC"
  "-DPLUGIN_THREAD_POOL_INFO=STATIC"
  "-DPLUGIN_TOKUDB=NO"
  "-DPLUGIN_TYPE_MYSQL_JSON=DYNAMIC"
  "-DPLUGIN_TYPE_MYSQL_TIMESTAMP=DYNAMIC"
  "-DPLUGIN_TYPE_TEST=DYNAMIC"
  "-DPLUGIN_USER_VARIABLES=STATIC"
  "-DWITHOUT_PACKED_SORT_KEYS=OFF"
  "-DWITHOUT_SERVER=OFF"
  "-DWITH_ASAN=OFF"
  "-DWITH_DBUG_TRACE=ON"
  "-DWITH_EMBEDDED_SERVER=OFF"
  "-DWITH_EXTRA_CHARSETS=all"
  "-DWITH_GPROF=OFF"
  "-DWITH_INNODB_AHI=ON"
  "-DWITH_INNODB_EXTRA_DEBUG=OFF"
  "-DWITH_INNODB_PMEM=ON"
  "-DWITH_INNODB_ROOT_GUESS=ON"
  "-DWITH_LIBAIO=OFF"
  "-DWITH_LIBFMT=auto"
  "-DWITH_LIBWRAP=OFF"
  "-DWITH_MSAN=OFF"
  "-DWITH_MYSQLD_LDFLAGS="
  "-DWITH_NUMA=AUTO"
  "-DWITH_PCRE=auto"
  "-DWITH_PIC=OFF"
  "-DWITH_PROTECT_STATEMENT_MEMROOT=ON"
  "-DWITH_READLINE=OFF"
  "-DWITH_SAFEMALLOC=AUTO"
  "-DWITH_SBOM=OFF"
  "-DWITH_SSL=yes"
  "-DWITH_SYSTEMD=auto"
  "-DWITH_TSAN=OFF"
  "-DWITH_UBSAN=OFF"
  "-DWITH_UNIT_TESTS=OFF"
  "-DWITH_URING=OFF"
  "-DWITH_VALGRIND=OFF"
  "-DWITH_WSREP=OFF"
  "-DWITH_WSREP_ALL=OFF"
  "-DWITH_ZLIB=system"
)
cmake -S "$SOURCE_DIR" -B "$BUILD_DIR" -G 'Unix Makefiles' "${CMAKE_OPTIONS[@]}"
cmake --build "$BUILD_DIR" --parallel "$JOBS"
cmake --install "$BUILD_DIR"
"$PREFIX/bin/mariadbd" --no-defaults --version
printf 'Installed: %s\n' "$PREFIX"
